@pytest.mark.parametrize("case_id, title, text, expected", CASES, ids=[case[0] for case in CASES])
async def test_place_is_never_guessed(forest, case_id, title, text, expected):
    scope = await classify_document(title, text, forest, FakeLLM({"kind": "unclear", "value": ""}))
    if expected.startswith("split:"):
        assert scope is not None and scope.encode() == expected
    else:
        assert scope is None if expected == "ask" else scope is None or scope.encode() == expected
